#!/usr/bin/env python3
"""Supplemental diagnostics; observer overhead means this is not an uninstrumented baseline."""
import threading,time,json,subprocess,pathlib,urllib.request
import argparse
parser=argparse.ArgumentParser(description='Observe a running disposable native lab; logs omit credentials and entity identifiers.')
parser.add_argument('context',type=pathlib.Path,help='Private context.json generated by run_native_load.py')
parser.add_argument('output',type=pathlib.Path,help='Observation JSONL output')
args=parser.parse_args()
c=json.loads(args.context.read_text());out=args.output.open('a',buffering=1);lock=threading.Lock()
def emit(kind,**data):
 with lock:out.write(json.dumps({'time':time.time(),'kind':kind,**data})+'\n')
def lag():
 while True:
  start=time.monotonic();time.sleep(.02);elapsed=time.monotonic()-start
  if elapsed>.07:emit('host_scheduler_lag',delay_ms=round((elapsed-.02)*1000,3))
def db():
 p=subprocess.Popen([c['pg_bin']+'/psql',c['admin_url'],'-X','-At','-v','ON_ERROR_STOP=1'],stdin=subprocess.PIPE,stdout=subprocess.PIPE,stderr=subprocess.DEVNULL,text=True,bufsize=1)
 sql="SELECT json_build_object('active',count(*) FILTER (WHERE state='active'),'idle_in_transaction',count(*) FILTER (WHERE state='idle in transaction'),'waiting',coalesce(json_agg(json_build_object('state',state,'wait_type',wait_event_type,'wait',wait_event)) FILTER (WHERE pid<>pg_backend_pid() AND state<>'idle'),'[]')) FROM pg_stat_activity WHERE datname=current_database();\n"
 try:
  while True:
   start=time.monotonic();p.stdin.write(sql);p.stdin.flush();line=p.stdout.readline()
   if not line:break
   emit('db_probe',duration_ms=round((time.monotonic()-start)*1000,3),activity=json.loads(line));time.sleep(.2)
 finally:p.terminate();p.wait()
def http():
 while True:
  start=time.monotonic()
  try:
   text=urllib.request.urlopen(f"http://127.0.0.1:{c['opsport']}/metrics",timeout=2).read().decode()
   vals={k:float(v) for k,v in (l.split() for l in text.splitlines()) if k in ['relation_guard_pool_idle','relation_guard_pool_size','relation_guard_pool_acquire_timeouts_total','relation_guard_errors_total','relation_guard_requests_total']}
   emit('app_probe',duration_ms=round((time.monotonic()-start)*1000,3),metrics=vals)
  except Exception as e:emit('app_probe_error',error=type(e).__name__)
  time.sleep(.2)
threading.Thread(target=lag,daemon=True).start();threading.Thread(target=http,daemon=True).start();db()
